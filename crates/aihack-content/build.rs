use std::{
    env, fs,
    path::{Path, PathBuf},
};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let items_path = manifest_dir.join("src/data/items.toml");
    let monsters_path = manifest_dir.join("src/data/monsters.toml");

    println!("cargo:rerun-if-changed={}", items_path.display());
    println!("cargo:rerun-if-changed={}", monsters_path.display());

    let items = parse_items(&read_file(&items_path));
    let monsters = parse_monsters(&read_file(&monsters_path));

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let mut generated = String::new();
    generated.push_str(
        "// @generated by crates/aihack-content/build.rs from items.toml & monsters.toml\n",
    );
    generated.push_str(&format!(
        "pub const GENERATED_ITEM_COUNT: usize = {};\n",
        items.len()
    ));
    generated.push_str(&format!(
        "pub const GENERATED_MONSTER_COUNT: usize = {};\n",
        monsters.len()
    ));
    generated.push_str("pub const GENERATED_CANONICAL_ITEM_KINDS: &[(&str, &str)] = &[\n");
    for item in &items {
        generated.push_str(&format!("    ({:?}, {:?}),\n", item.id, item.kind));
    }
    generated.push_str("];\n");
    generated.push_str("pub const GENERATED_ITEM_APPEARANCE_POOLS: &[(&str, &str)] = &[\n");
    for item in &items {
        if let Some(pool) = &item.unidentified_pool {
            generated.push_str(&format!("    ({:?}, {:?}),\n", item.id, pool));
        }
    }
    generated.push_str("];\n");
    generated.push_str("pub const GENERATED_MONSTER_IDS: &[&str] = &[\n");
    for monster in &monsters {
        generated.push_str(&format!("    {:?},\n", monster));
    }
    generated.push_str("];\n");

    fs::write(out_dir.join("generated_catalog.rs"), generated)
        .expect("failed to write generated_catalog.rs");
}

fn read_file(path: &Path) -> String {
    fs::read_to_string(path).unwrap_or_else(|err| {
        panic!("failed to read {}: {err}", path.display());
    })
}

struct ItemEntry {
    id: String,
    kind: String,
    unidentified_pool: Option<String>,
}

fn parse_items(src: &str) -> Vec<ItemEntry> {
    let mut entries = Vec::new();
    let mut current: Option<(Option<String>, Option<String>, Option<String>)> = None;

    for raw_line in src.lines() {
        let line = raw_line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if line == "[[item]]" {
            if let Some((Some(id), Some(kind), pool)) = current.take() {
                entries.push(ItemEntry {
                    id,
                    kind,
                    unidentified_pool: pool,
                });
            }
            current = Some((None, None, None));
            continue;
        }
        if line.starts_with('[') {
            if let Some((Some(id), Some(kind), pool)) = current.take() {
                entries.push(ItemEntry {
                    id,
                    kind,
                    unidentified_pool: pool,
                });
            }
            continue;
        }
        if let Some((ref mut id, ref mut kind, ref mut pool)) = current {
            if let Some(val) = extract_string_field(line, "id") {
                *id = Some(val);
            } else if let Some(val) = extract_string_field(line, "kind") {
                *kind = Some(val);
            } else if let Some(val) = extract_string_field(line, "unidentified_pool") {
                *pool = Some(val);
            }
        }
    }
    if let Some((Some(id), Some(kind), pool)) = current.take() {
        entries.push(ItemEntry {
            id,
            kind,
            unidentified_pool: pool,
        });
    }
    entries
}

fn parse_monsters(src: &str) -> Vec<String> {
    let mut ids = Vec::new();
    let mut in_monster = false;

    for raw_line in src.lines() {
        let line = raw_line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if line == "[[monster]]" {
            in_monster = true;
            continue;
        }
        if line.starts_with('[') {
            in_monster = false;
            continue;
        }
        if in_monster {
            if let Some(val) = extract_string_field(line, "id") {
                ids.push(val);
                in_monster = false;
            }
        }
    }
    ids
}

fn extract_string_field(line: &str, expected_key: &str) -> Option<String> {
    let (lhs, rhs) = line.split_once('=')?;
    if lhs.trim() != expected_key {
        return None;
    }
    let val = rhs.trim();
    if let Some(stripped) = val.strip_prefix('"') {
        if let Some(end) = stripped.find('"') {
            return Some(stripped[..end].to_owned());
        }
    }
    if let Some(stripped) = val.strip_prefix('\'') {
        if let Some(end) = stripped.find('\'') {
            return Some(stripped[..end].to_owned());
        }
    }
    None
}
